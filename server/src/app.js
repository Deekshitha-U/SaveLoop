import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import userRoutes from './routes/userRoutes.js';
import bookmarkRoutes from './routes/bookmarkRoutes.js';
import categoryRoutes from './routes/categoryRoutes.js';
import reminderRoutes from './routes/reminderRoutes.js';
import searchRoutes from './routes/searchRoutes.js';
import aiRoutes from './routes/aiRoutes.js';
import adminRoutes from './routes/adminRoutes.js';
import { authenticate } from './middleware/authenticate.js';
import { errorHandler } from './middleware/errorHandler.js';
import { httpError } from './utils/httpError.js';
export const app = express();
app.disable('x-powered-by');
app.use(helmet());
const allowed = (process.env.CLIENT_ORIGIN || 'http://localhost:5173').split(',').map((s) => s.trim());
app.use(cors({ origin: (origin, callback) => !origin || allowed.includes(origin) ? callback(null, true) : callback(httpError(403, 'CORS origin not allowed')) }));
app.use(express.json({ limit: '100kb' }));
app.use(morgan('tiny'));
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 800, standardHeaders: 'draft-7', legacyHeaders: false }));
app.get('/api/health', (_req, res) => res.json({ status: 'ok', app: 'SaveLoop API' }));
app.use('/api/users', userRoutes);
app.use('/api/bookmarks', authenticate, bookmarkRoutes);
app.use('/api/categories', authenticate, categoryRoutes);
app.use('/api/reminders', authenticate, reminderRoutes);
app.use('/api/search', authenticate, searchRoutes);
app.use('/api/ai', authenticate, aiRoutes);
app.use('/api/admin', authenticate, adminRoutes);
app.use((_req, _res, next) => next(httpError(404, 'Route not found')));
app.use(errorHandler);
